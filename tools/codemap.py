#!/usr/bin/env python3
"""airx codemap — read the whole repo and write a navigable MAP + coverage ledger into MEMORY.md.

This is the "read the entire codebase, build a proper memory plan" step — done the thesis-safe way.
It does NOT generate prose memory (that stays VERIFIED and per-module, authored via /airx:memory). It
builds the **index-first ROUTER**: every module ranked by churn, its key declared types, whether it has a
note yet, and keywords — so an agent loads MEMORY.md (this map) and then the ONE note matching its task,
never the whole memory. Comprehensive on disk, lean in context.

Deterministic, stdlib only, no LLM. Composes init.rank_modules (churn ranking) + init._module_base
(module dirs) and re-uses the note-coverage signal. Writes a generated block between markers into
`.airx/ai_memory/MEMORY.md`, preserving everything outside it (the human-curated Spine, etc.).

    python3 codemap.py <wiki-dir>
Exit: 0 (advisory); 2 on usage error.
"""
from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import airxpaths as ap


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    return m


vc = _load("airx_vc", HERE / "verify-citations.py")
init = _load("airx_init", HERE / "init.py")

MAP_BEGIN = "<!-- airx:map:begin (generated by codemap — regenerate with /airx:memory, don't hand-edit) -->"
MAP_END = "<!-- airx:map:end -->"

# A declared type/class name across the common stacks (java/kt/cs/go/ts/py). Map-only heuristic, not
# verification — the agent verifies before citing.
_DECL = re.compile(r"\b(?:class|interface|enum|struct|trait|object)\s+([A-Z][A-Za-z0-9_]*)")
_CODE_EXT = {".java", ".kt", ".py", ".go", ".ts", ".js", ".rb", ".cs", ".scala"}
_SKIP = {".git", ".github", ".idea", ".vscode", "target", "build", "dist", "out", "bin",
         "node_modules", "__pycache__", "venv", ".venv", ".airx", "ai_memory",
         "ai_documentation", "ai_knowledge_base"}


def key_types(module_dir: Path, limit: int = 6) -> list:
    """Top declared type names under a module dir (first-seen order) — the 'what's in here' hint."""
    if not module_dir.is_dir():
        return []
    seen: list[str] = []
    for p in sorted(module_dir.rglob("*")):
        if not p.is_file() or p.suffix not in _CODE_EXT:
            continue
        if any(part in _SKIP for part in p.parts):
            continue
        try:
            for m in _DECL.finditer(p.read_text(errors="ignore")):
                t = m.group(1)
                if t not in seen:
                    seen.append(t)
                    if len(seen) >= limit:
                        return seen
        except Exception:
            continue
    return seen


def covered_modules(mem: Path) -> set:
    """Module names that already have a note — by note stem (reference_<m>.md / project_<m>.md)."""
    covered = set()
    if not mem.is_dir():
        return covered
    for p in mem.glob("**/*.md"):
        if (p.name.startswith("_") or p.name in vc.NON_NOTES
                or ".cache" in p.parts or "_seed" in p.parts):
            continue
        for pre in ("reference_", "project_"):
            if p.stem.startswith(pre):
                covered.add(p.stem[len(pre):])
    return covered


def build_map_block(repo: Path, mem: Path) -> str:
    ranked = init.rank_modules(repo)
    base, _ = init._module_base(repo)
    covered = covered_modules(mem)
    lines = [MAP_BEGIN,
             "## Codebase map — index-first router (generated)",
             "> Load this, then the ONE note whose keywords match your task. Ranked by recent git churn.",
             "",
             "| Area | Churn | Key types | Note | Keywords |",
             "|---|---|---|---|---|"]
    n_cov = 0
    for name, churn in ranked:
        types = key_types(base / name)
        has = name in covered
        n_cov += 1 if has else 0
        note = f"`reference_{name}.md` ✓" if has else "— _TBD_"
        kw = ", ".join([name] + [t.lower() for t in types[:3]])
        tcell = ", ".join(f"`{t}`" for t in types[:5]) or "_TBD_"
        lines.append(f"| {name} | {churn} | {tcell} | {note} | {kw} |")
    total = len(ranked)
    lines.append("")
    lines.append(f"**Coverage:** {n_cov}/{total} areas have a verified note."
                 + ("" if n_cov == total else
                    f"  NEXT: `/airx:memory "
                    f"{next((n for n, _ in ranked if n not in covered), '')}`"))
    lines.append(MAP_END)
    return "\n".join(lines)


def write_map(mem_index: Path, block: str) -> None:
    """Replace the generated block between markers; append it if absent. Never touches outside text."""
    text = mem_index.read_text(errors="ignore") if mem_index.is_file() else "# Project Memory — index\n"
    if MAP_BEGIN in text and MAP_END in text:
        pre = text[:text.index(MAP_BEGIN)]
        post = text[text.index(MAP_END) + len(MAP_END):]
        text = pre + block + post
    else:
        text = text.rstrip() + "\n\n" + block + "\n"
    mem_index.write_text(text)


def main() -> int:
    if len(sys.argv) != 2:
        print("usage: codemap.py <wiki-dir>", file=sys.stderr)
        return 2
    wiki = Path(sys.argv[1]).resolve()
    if not wiki.is_dir():
        print(f"error: wiki {wiki} not found", file=sys.stderr)
        return 2
    repo = vc.repo_from_manifest(wiki)
    if repo is None or not repo.is_dir():
        print("airx codemap — no resolvable repo_path in manifest (run /airx:init first).")
        return 0
    mem = ap.memory(wiki)
    mem.mkdir(parents=True, exist_ok=True)
    block = build_map_block(repo, mem)
    write_map(mem / "MEMORY.md", block)
    n_areas = block.count("\n| ") - 1   # rows minus header
    print(f"airx codemap ✓  wrote the codebase map into {mem/'MEMORY.md'} ({max(0, n_areas)} areas)")
    print("  it's the index-first router: load MEMORY.md, then the one note matching your task.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
